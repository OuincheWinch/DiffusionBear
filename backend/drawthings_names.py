"""Parse and map Draw Things internal tensor names.

Draw Things identifies a tensor by a bracketed scope plus a suffix, e.g.
`__unet__[t-25-0]__up__` for a LoRA up-projection, or `__dit__[t-x_v-9-1]`
for a FLUX weight. The grammar and the name tables were transcribed from
`drawthingsai/draw-things-community` at revision 060f99d -- specifically
`Libraries/SwiftDiffusion/Sources/Mappings/ModelMapping.swift` and
`Libraries/ModelOp/Sources/LoRAImporter.swift`.

Nothing here guesses. An unmapped name raises `NameMappingError` quoting the
offending tensor, because a plausible-but-wrong key loads silently and then
generates garbage.
"""

import json
import re
from dataclasses import dataclass
from pathlib import Path

# Prefixes Draw Things writes. `__te3__` deliberately does not exist upstream.
KNOWN_PREFIXES = frozenset(
    {
        "__unet__",
        "__unet_fixed__",
        "__text_model__",
        "__te2__text_model__",
        "__dit__",
        "__stage_c__",
        "__stage_c_fixed__",
    }
)

_NAME_RE = re.compile(r"^(?P<prefix>__\w+__?)\[(?P<body>[^\]]+)\](?:__(?P<part>up|down)__)?$")
# The scope is optional: SD/SDXL write an anonymous body (`t-25-0`) while
# FLUX writes a named one (`t-x_v-9-1`). The scope group must be optional
# rather than `[^-]*`, which would greedily eat the layer digits and never
# match the anonymous form.
_BODY_RE = re.compile(r"^t-(?:(?P<scope>[^-]+)-)?(?P<layer>\d+)-(?P<param>\d+)$")


_NAME_MAP_PATH = Path(__file__).with_name("drawthings_name_map.json")
_name_map_cache = None


def load_name_map():
    """Return the harvested `{table: {diffusers_key: [ids]}}` mapping.

    Generated by `tools/harvest_model_mapping.py` from Draw Things' own
    `ModelMapping.swift` at revision 060f99d and committed so neither the app
    nor its tests need the Swift source at runtime.
    """
    global _name_map_cache
    if _name_map_cache is None:
        if not _NAME_MAP_PATH.exists():
            raise NameMappingError(
                f"missing {_NAME_MAP_PATH.name}; regenerate it with "
                "tools/harvest_model_mapping.py"
            )
        with open(_NAME_MAP_PATH) as fh:
            _name_map_cache = json.load(fh)
    return _name_map_cache


# SDXL block indices. Draw Things stores SD/SDXL in kohya/compel layout, but
# DiffusionBear's `sdxl_engine._map_kohya_key` only knows {4,5,7,8} and returns
# None for everything else -- and its caller drops unmapped keys silently. So we
# emit diffusers paths ourselves.
#
# The `.1` (attention) entries are cross-checked against `_map_kohya_key`, which
# already encodes 4->down_blocks.1.attentions.0, 5->.1, 7->down_blocks.2.attentions.0,
# 8->.1. The `.0` (resnet) entries are inferred from SDXL's block structure and
# MUST be verified against a real UNet in the Task 8 gate before shipping.
_BLOCK_MAP_PATH = Path(__file__).with_name("drawthings_sdxl_block_map.json")
_block_map = None

# DT writes `middle_block`, diffusers writes `mid_block`; the derived map is
# keyed by direction, so translate before lookup.
_DIRECTION_RE = re.compile(
    r"^(?P<dir>input_blocks|output_blocks|middle_block|mid_block)\.(?P<a>\d+)(?:\.(?P<b>\d+))?\."
)
_BLOCK_PREFIX = {
    "input_blocks": "down",
    "output_blocks": "up",
    "middle_block": "mid",
    "mid_block": "mid",
}


def load_block_map():
    """Load the derived kohya slot -> diffusers slot map.

    Generated by `tools/derive_sdxl_block_map.py` by zipping Draw Things'
    ordered slots against a real diffusers SDXL UNet module tree, and refusing
    to emit anything unless the per-class counts agree. Never hand-written.
    """
    global _block_map
    if _block_map is None:
        if not _BLOCK_MAP_PATH.exists():
            raise NameMappingError(
                f"missing {_BLOCK_MAP_PATH.name}; regenerate it with "
                "tools/derive_sdxl_block_map.py"
            )
        with open(_BLOCK_MAP_PATH) as fh:
            _block_map = json.load(fh)
    return _block_map


_STRIP_PREFIXES = (
    "cond_stage_model.transformer.text_model.",
    "cond_stage_model.model.",
    "cond_stage_model.transformer.",
    "cond_stage_model.",
    "model.diffusion_model.",
    "diffusion_model.",
    "model.",
)

# Scope: SDXL only. DiffusionBear's SDXL engine loads SDXL models exclusively, and
# the SD 1.x / SD 2.x kohya block layouts differ in ways we have not verified --
# mapping them by inference would attach weights to the wrong modules.
SDXL_TABLES = ("UNetXLBase", "CLIPTextModel", "OpenCLIPTextModelG")

# Which tables each Draw Things prefix maps to, for SDXL.
PREFIX_TO_TABLES = {
    "__unet__": ("UNetXLBase",),
    "__unet_fixed__": ("UNetXLBaseFixed",),
    "__text_model__": ("CLIPTextModel",),
    "__te2__text_model__": ("OpenCLIPTextModelG",),
}

_TEXT_TABLES = frozenset(SDXL_TABLES[1:])


# `__te2__text_model__` is the one prefix whose target layout is not diffusers.
#
# Draw Things names it `OpenCLIPTextModelG` because its text tables spell
# open_clip's `CLIPTransformer`: `transformer.resblocks.N.attn.in_proj_weight`,
# `attn.out_proj`, `mlp.c_fc`, `mlp.c_proj`. But the SDXL engine's
# `text_encoder_2` is a HuggingFace `CLIPTextModelWithProjection`, which has no
# `transformer`, no `resblocks` and no fused `in_proj_weight` -- it has
# `text_model.encoder.layers.N.self_attn.{q,k,v,out}_proj` and `mlp.fc{1,2}`.
# Verified against juggernaut-xl-lightning's real `text_encoder_2`: 193 Linear
# modules, none reachable by Draw Things' spelling.
#
# So `attn.in_proj_weight` is one DT weight of (3840, 1280) standing against
# three separate (1280, 1280) Linears. The three Draw Things slots are three
# *independent* LoRAs -- measured on add_detail_xl_lora_f16.ckpt, their down
# matrices all differ -- so each slot is its own target and nothing has to be
# split after the fact.
#
# Slot order is q, k, v and that is not a guess. DT's own loader
# (`Models/OpenCLIPTextModel.swift` lines 143-154, revision 060f99d) slices the
# fused weight as
#     toqueriess <- in_proj_weight[0..<E]
#     tokeyss    <- in_proj_weight[E..<2E]
#     tovaluess  <- in_proj_weight[2E..<3E]
# and the harvested row lists the ids in ascending order `t-(i*8+3)`, `t-(i*8+4)`,
# `t-(i*8+5)`, so id order is row-block order is q, k, v.
#
# Values are `(tail_template, slot_count)`. A tail template with three slots is
# indexed by the slot's position in the harvested row's id list, which is the
# order Draw Things lists them: q, k, v.
_TE2_LAYOUT = {
    "attn.in_proj_weight": ("self_attn.{qkv}_proj", 3),
    "attn.in_proj_bias": (None, 3),
    "attn.out_proj": ("self_attn.out_proj", 1),
    "mlp.c_fc": ("mlp.fc1", 1),
    "mlp.c_proj": ("mlp.fc2", 1),
}

# ln_1, ln_2, positional_embedding, token_embedding and ln_final have no entry.
# They are LayerNorms and an Embedding; `load_multilora` only attaches a LoRA to
# a Linear or QuantizedLinear, so there is no module to target. They are absent
# from every real FLUX/SDXL LoRA measured, and refusing is the correct answer
# rather than emitting a key that fails at load time.

_QKV_NAMES = ("q", "k", "v")
_TE2_LAYERS = 32


def _te2_tail(path, position):
    """Rewrite one normalised `OpenCLIPTextModelG` path to HF's layout.

    Returns the module path without its `text_model.` prefix, or `None` when
    the path has no HF counterpart. `position` is the slot's index in the
    harvested row.
    """
    match = _TE2_RESBLOCK_RE.match(path)
    if match is None:
        return None
    layer = int(match.group("layer"))
    if not 0 <= layer < _TE2_LAYERS:
        return None
    tail = match.group("tail")
    entry = _TE2_LAYOUT.get(tail)
    if entry is None:
        return None
    template, slots = entry
    if template is None or not 0 <= position < slots:
        return None
    if slots == 3:
        template = template.replace("{qkv}", _QKV_NAMES[position])
    return f"encoder.layers.{layer}.{template}"


_TE2_RESBLOCK_RE = re.compile(
    r"^transformer\.resblocks\.(?P<layer>\d+)\.(?P<tail>.+)$"
)


class NameMappingError(ValueError):
    """Raised when a Draw Things tensor name cannot be parsed or mapped."""


def normalise_key(key):
    """Strip a harvested key down to a diffusers module path."""
    path = key
    for prefix in _STRIP_PREFIXES:
        if path.startswith(prefix):
            path = path[len(prefix):]
            break
    if path.endswith(".weight") or path.endswith(".bias"):
        path = path.rsplit(".", 1)[0]
    return path


def kohya_to_diffusers(path):
    """Rewrite a kohya SDXL path into its diffusers equivalent.

    Returns `None` when the path's block slot has no derived counterpart --
    a guess here would attach weights to the wrong module. Paths with no
    recognised block prefix (e.g. `time_embed.0`) pass through unchanged.
    """
    match = _DIRECTION_RE.match(path)
    if match is None:
        return path
    direction = _BLOCK_PREFIX[match.group("dir")]
    slot = f"{direction}.{match.group('a')}"
    # middle_block carries one index; the derived map keys it as mid.<a>.0
    if match.group("b") is not None:
        slot += f".{match.group('b')}"
    elif direction == "mid":
        slot += ".0"
    target = load_block_map().get(slot)
    if target is None:
        return None
    tail = path[match.end():]
    return f"{target}.{tail}" if tail else target


def build_reverse_map(tables):
    """Invert `{table: {key: [ids]}}` into `{"<table>::<id>": normalised key}`.

    Raises `NameMappingError` if two distinct paths claim the same id, which
    would otherwise silently drop weights.
    """
    reverse = {}
    for table, rows in tables.items():
        for key, ids in rows.items():
            path = normalise_key(key)
            for i in ids:
                entry = f"{table}::{i}"
                if entry in reverse and reverse[entry] != path:
                    raise NameMappingError(
                        f"{entry} is claimed by both {reverse[entry]!r} and {path!r}"
                    )
                reverse[entry] = path
    return reverse


_slots_cache = None


def _slots():
    """Return `{(prefix, tid): (table, normalised_path, position, total)}`.

    The plain reverse map throws away which slot of a fused row an id was, and
    `OpenCLIPTextModelG`'s fused `attn.in_proj_weight` needs exactly that: its
    three ids are q, k and v in the order Draw Things lists them.
    """
    global _slots_cache
    if _slots_cache is None:
        tables = load_name_map()
        # Not defensive: a duplicate id inside one table collapses two rows onto
        # one under a plain assignment, and the converter would then emit a file
        # with a weight silently missing. `build_reverse_map` raises instead.
        for table in tables:
            build_reverse_map({table: tables[table]})
        index = {}
        grouped = group_fused(tables)
        for prefix, table_list in PREFIX_TO_TABLES.items():
            for table in table_list:
                for key, entries in grouped[table].items():
                    path = normalise_key(key)
                    for position, tid in entries:
                        index[(prefix, tid)] = (table, path, position, len(entries))
        _slots_cache = index
    return _slots_cache


# The module path suffixes that have an `nn.Linear` behind them, once a kohya
# SDXL path has been rewritten to its diffusers equivalent.
#
# Matched as suffixes rather than by the last path component, because `norm_key`
# cannot tell `attn1.to_out.0` (a Linear) from `in_layers.0` (a ModuleList index
# onto a Conv2d) -- both reduce to the leaf `0`.
#
# This is an allowlist on purpose. `load_multilora` only attaches a LoRA to a
# `Linear` or `QuantizedLinear`, so any other row -- a LayerNorm's affine
# (`norm`, `norm1/2/3`, `layer_norm1/2`, `final_layer_norm`), an Embedding
# (`position_embedding`, `token_embedding`), a Conv2d (`conv`, `op`, or a bare
# index into `in_layers`/`out_layers`), or `skip_connection` -- would make it
# raise `LoRA target ... is LayerNorm` and refuse the entire file. An allowlist
# means an unrecognised name is refused too, which is the safe direction: a new
# row in a future Draw Things revision stops the conversion instead of emitting
# a key that cannot load.
SDXL_LINEAR_SUFFIXES = (
    ".attn1.to_q", ".attn1.to_k", ".attn1.to_v", ".attn1.to_out.0",
    ".attn2.to_q", ".attn2.to_k", ".attn2.to_v", ".attn2.to_out.0",
    ".attn.to_q", ".attn.to_k", ".attn.to_v", ".attn.to_out.0",
    ".ff.net.0.proj", ".ff.net.2",
    ".ff_context.net.0.proj", ".ff_context.net.2",
    ".self_attn.q_proj", ".self_attn.k_proj", ".self_attn.v_proj",
    ".self_attn.out_proj",
    ".mlp.fc1", ".mlp.fc2", ".mlp.c_fc", ".mlp.c_proj",
    ".proj_in", ".proj_out", ".time_emb_proj",
    ".x_embedder", ".context_embedder",
)


def _has_linear(path):
    """True when `path` names an `nn.Linear` in the diffusers layout."""
    return path.endswith(SDXL_LINEAR_SUFFIXES)


def resolve_sd(prefix, layer, param):
    """Resolve an SD/SDXL internal id to a diffusers module path, or `None`.

    `__te2__text_model__` goes through `_te2_tail`: the engine's `text_encoder_2`
    is a HuggingFace `CLIPTextModelWithProjection`, which shares none of
    open_clip's spelling, and its fused `in_proj_weight` is three separate
    projections there.
    """
    if prefix not in PREFIX_TO_TABLES:
        return None
    tid = f"t-{layer}-{param}"
    found = _slots().get((prefix, tid))
    if found is None:
        return None
    table, path, position, _total = found

    if table == "OpenCLIPTextModelG":
        tail = _te2_tail(path, position)
        return None if tail is None else "text_model." + tail

    # `CLIPTextModel` is rooted at `text_model`, like every other HF CLIP component.
    # The root is `text_model.encoder...`, NOT `encoder...`.
    #
    # This used to be the other way round, on a comment asserting that
    # `CLIPTextModel` "has no `text_model` attribute". That is false: `text_model` is
    # the standard HF layout, and what distinguishes
    # `CLIPTextModelWithProjection` is the `text_projection` weight, not the presence
    # of `text_model`. Loading the real `juggernaut-xl-lightning` pipeline settles it --
    # both `text_encoder` and `text_encoder_2` are `CLIPTextModel` and both root at
    # `text_model.encoder.layers.0...`, so `text_encoder_2` was already right and
    # `text_encoder` was wrong.
    #
    # The error was invisible until generation ran: the unit test built its expectation
    # from this same comment, and the stub-pipe gate built its module tree from the
    # keys the converter emitted, so a wrong key agreed with itself twice. Only the real
    # pipeline caught it -- "LoRA target text_encoder:encoder.layers.0.mlp.fc1 is
    # unavailable". See `ComponentRootTests`.
    path = kohya_to_diffusers(path)
    if path is None or not _has_linear(path):
        return None
    # Only the CLIPTextModel table gets the root. `kohya_to_diffusers` paths for the
    # UNet tables are already relative to the module the engine looks up directly.
    return "text_model." + path if table == "CLIPTextModel" else path


def slot_of(prefix, layer, param):
    """Return `(path, position, total)` for an SD/SDXL id, or `None`.

    `total` is how many ids share this weight. It is 1 for an ordinary row and
    greater than 1 only where Draw Things genuinely fuses one diffusers weight
    across several slots -- which, for `OpenCLIPTextModelG`, it does not, since
    its three `in_proj_weight` slots are three independent projections in the
    target model.
    """
    found = _slots().get((prefix, f"t-{layer}-{param}"))
    if found is None:
        return None
    _table, path, position, total = found
    if _table == "OpenCLIPTextModelG":
        return _slots_total(prefix, layer, param, path, position, total)
    return path, position, total


def _slots_total(prefix, layer, param, path, position, total):
    """`OpenCLIPTextModelG` slots are independent targets, never merged."""
    if _te2_tail(path, position) is None:
        return None
    return path, position, 1


def group_fused(tables):
    """Return `{table: {diffusers_key: [(position, tensor_id), ...]}}`.

    Draw Things splits some diffusers weights across several internal ids --
    `ff.net.0.proj` is stored as two slots, `attn.in_proj_weight` as three. The
    position inside the row's id list is the concatenation order, because
    `ModelWeightElement` defaults to `format: .O` with `offsets: nil`, which
    slices **axis 0** in array order. Getting the axis right still leaves a
    right-shaped wrong-valued array if the order is wrong, so the position is
    carried explicitly rather than left to dict order: the committed JSON is
    written with sorted keys, which is alphabetical, not declaration order.

    Keys are the harvested diffusers keys verbatim, `.weight` and `.bias`
    included. Grouping by the normalised module path instead would merge a
    Linear's weight row with its bias row into one group, and the caller would
    concatenate a bias into a weight.

    The result is nested per table because a diffusers key is not unique across
    tables: `CLIPTextModel` and `OpenCLIPTextModel` both spell
    `...text_model.final_layer_norm.bias` and give it different ids (`t-98-1`
    and `t-186-1`). Which table a tensor belongs to is decided by its prefix,
    not by its key. Within a table an id is already unique -- that is
    `build_reverse_map`'s contract, checked there.
    """
    return {
        table: {key: [(position, tid) for position, tid in enumerate(ids)]
                for key, ids in rows.items()}
        for table, rows in tables.items()
    }


